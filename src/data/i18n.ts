export function getCategoryLabel(cat: string, lang: AppLang): string {
  if (cat === 'all') return lang === 'ar' ? 'الكل' : 'Tous';
  const found = SERVICE_CATEGORIES.find((c) => c.id === cat);
  if (found) return lang === 'ar' ? found.ar : found.fr;

  const legacy: Record<string, { ar: string; fr: string }> = {
    construction: { ar: 'البناء والترميم', fr: 'Construction & Rénovation' },
    renovation: { ar: 'البناء والترميم', fr: 'Construction & Rénovation' },
    kitchen_bath: { ar: 'السيراميك والبلاط', fr: 'Céramique & Carrelage' },
    facades: { ar: 'البناء والترميم', fr: 'Construction & Rénovation' },
  };
  if (legacy[cat]) return legacy[cat][lang];
  return cat;
}

